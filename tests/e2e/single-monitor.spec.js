import { test, expect } from '@playwright/test'
import { uniqueCode, openControl, openBoard, home, away } from './helpers.js'

test('control page: click a score, shots, period or penalty time and type it', async ({ page, context }) => {
  const code = uniqueCode('typenum')
  await openControl(page, code)
  const board = await openBoard(context, code)
  await home(page).locator('.s').click()
  await page.getByLabel('type score').fill('3')
  await page.getByLabel('type score').press('Enter')
  await expect(home(page).locator('.s')).toHaveText('3')
  await expect(board.locator('.board .team').nth(0).locator('.score')).toHaveText('3')
  await away(page).locator('[data-edit="shots:away"]').click()
  await page.getByLabel('type shots').fill('17')
  await page.getByLabel('type shots').press('Enter')
  await expect(away(page).locator('[data-edit="shots:away"]')).toHaveText('17')
  await page.locator('.pv[data-edit="period"]').click()
  await page.getByLabel('type period').fill('ot')
  await page.getByLabel('type period').press('Enter')
  await expect(board.locator('.board .period b')).toHaveText('OT')
  // a wrong entry stays red and changes nothing
  await home(page).locator('.s').click()
  await page.getByLabel('type score').fill('abc')
  await page.getByLabel('type score').press('Enter')
  await expect(page.getByLabel('type score')).toHaveClass(/bad/)
  await page.getByLabel('type score').press('Escape')
  await expect(home(page).locator('.s')).toHaveText('3')
})

test('single monitor: only the scoreboard; click its numbers to type; START/STOP and keys still work', async ({ page, context }) => {
  const code = uniqueCode('single')
  await openControl(page, code)
  const tv = await openBoard(context, code)
  await page.getByRole('button', { name: /Single monitor/ }).click()
  await expect(page).toHaveURL(/view=single/)
  await expect(page.locator('.singleview .board')).toBeVisible()
  await expect(page.locator('.clockcard')).toBeHidden()
  await page.locator('.singleview .board .clock').click()
  await page.getByLabel('type clock').fill('1000')
  await page.getByLabel('type clock').press('Enter')
  await expect(page.locator('.singleview .board .clock')).toHaveText('10:00')
  await expect(tv.locator('.board .clock')).toHaveText('10:00')
  await page.locator('.singleview .board .team').nth(1).locator('.score').click()
  await page.getByLabel('type score').fill('2')
  await page.getByLabel('type score').press('Enter')
  await expect(tv.locator('.board .team').nth(1).locator('.score')).toHaveText('2')
  await page.locator('.singlebar').getByRole('button', { name: 'START', exact: true }).click()
  await expect(page.locator('.singlebar').getByRole('button', { name: 'STOP', exact: true })).toBeVisible()
  await page.keyboard.press('Space')
  await expect(page.locator('.singlebar').getByRole('button', { name: 'START', exact: true })).toBeVisible()
  // the penalty sheet opens over the scoreboard
  await page.getByRole('button', { name: 'add penalty home (single monitor)' }).click()
  await expect(page.locator('.sheet')).toBeVisible()
  await page.keyboard.press('Escape')
  await page.locator('.sheet-bg').click({ position: { x: 5, y: 5 } }).catch(() => {})
  await page.getByRole('button', { name: /Control panel/ }).click()
  await expect(page.locator('.clockcard')).toBeVisible()
  await expect(page).not.toHaveURL(/view=single/)
})
